export function translate(lang: string, text: string, vars?: Record<string, string | number>) {
  let out = (lang === "th" && TH[text]) || text;
  if (vars) for (const [k, v] of Object.entries(vars)) out = out.replaceAll(`{${k}}`, String(v));
  return out;
}

export function useT() {
  const { appearance } = useTheme();
  const lang = appearance.language;
  return useCallback((text: string, vars?: Record<string, string | number>) => translate(lang, text, vars), [lang]);
}
